```sql
-- FYNVERA Community Features
-- Run schema.sql first, then run this file.
-- Compatible with articles.user_id (not articles.author_id).

-- 1. Author profiles
CREATE TABLE IF NOT EXISTS public.author_profiles (
    user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    display_name TEXT,
    username TEXT UNIQUE,
    bio TEXT,
    avatar_url TEXT,
    website_url TEXT,
    x_url TEXT,
    tiktok_url TEXT,
    facebook_url TEXT,
    telegram_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Article reactions: like / dislike
CREATE TABLE IF NOT EXISTS public.article_reactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id UUID NOT NULL REFERENCES public.articles(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    reaction TEXT NOT NULL CHECK (reaction IN ('like', 'dislike')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (article_id, user_id)
);

-- 3. Article comments
CREATE TABLE IF NOT EXISTS public.article_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id UUID NOT NULL REFERENCES public.articles(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    parent_id BIGINT REFERENCES public.article_comments(id) ON DELETE CASCADE,
    content TEXT NOT NULL CHECK (char_length(trim(content)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Saved/bookmarked articles
CREATE TABLE IF NOT EXISTS public.article_bookmarks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id UUID NOT NULL REFERENCES public.articles(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (article_id, user_id)
);

-- 5. Author follow / unfollow
CREATE TABLE IF NOT EXISTS public.author_follows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    followed_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (follower_id <> followed_id),
    UNIQUE (follower_id, followed_id)
);

-- 6. Indexes
CREATE INDEX IF NOT EXISTS idx_article_reactions_article
    ON public.article_reactions(article_id);

CREATE INDEX IF NOT EXISTS idx_article_reactions_user
    ON public.article_reactions(user_id);

CREATE INDEX IF NOT EXISTS idx_article_comments_article
    ON public.article_comments(article_id, created_at);

CREATE INDEX IF NOT EXISTS idx_article_comments_user
    ON public.article_comments(user_id);

CREATE INDEX IF NOT EXISTS idx_article_bookmarks_user
    ON public.article_bookmarks(user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_author_follows_follower
    ON public.author_follows(follower_id);

CREATE INDEX IF NOT EXISTS idx_author_follows_followed
    ON public.author_follows(followed_id);

CREATE INDEX IF NOT EXISTS idx_author_profiles_username
    ON public.author_profiles(username);

-- 7. Enable Row Level Security
ALTER TABLE public.author_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.article_reactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.article_comments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.article_bookmarks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.author_follows ENABLE ROW LEVEL SECURITY;

-- 8. Author profile policies
DROP POLICY IF EXISTS "Author profiles are publicly readable"
    ON public.author_profiles;

CREATE POLICY "Author profiles are publicly readable"
    ON public.author_profiles
    FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Users can insert their own author profile"
    ON public.author_profiles;

CREATE POLICY "Users can insert their own author profile"
    ON public.author_profiles
    FOR INSERT
    TO authenticated
    WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can update their own author profile"
    ON public.author_profiles;

CREATE POLICY "Users can update their own author profile"
    ON public.author_profiles
    FOR UPDATE
    TO authenticated
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

-- 9. Reactions policies
DROP POLICY IF EXISTS "Published article reactions are publicly readable"
    ON public.article_reactions;

CREATE POLICY "Published article reactions are publicly readable"
    ON public.article_reactions
    FOR SELECT
    USING (
        EXISTS (
            SELECT 1
            FROM public.articles a
            WHERE a.id = article_id
              AND a.status = 'published'
        )
    );

DROP POLICY IF EXISTS "Authenticated users can add their own reactions"
    ON public.article_reactions;

CREATE POLICY "Authenticated users can add their own reactions"
    ON public.article_reactions
    FOR INSERT
    TO authenticated
    WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can update their own reactions"
    ON public.article_reactions;

CREATE POLICY "Users can update their own reactions"
    ON public.article_reactions
    FOR UPDATE
    TO authenticated
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can delete their own reactions"
    ON public.article_reactions;

CREATE POLICY "Users can delete their own reactions"
    ON public.article_reactions
    FOR DELETE
    TO authenticated
    USING (auth.uid() = user_id);

-- 10. Comments policies
DROP POLICY IF EXISTS "Published article comments are publicly readable"
    ON public.article_comments;

CREATE POLICY "Published article comments are publicly readable"
    ON public.article_comments
    FOR SELECT
    USING (
        EXISTS (
            SELECT 1
            FROM public.articles a
            WHERE a.id = article_id
              AND a.status = 'published'
        )
    );

DROP POLICY IF EXISTS "Authenticated users can add comments"
    ON public.article_comments;

CREATE POLICY "Authenticated users can add comments"
    ON public.article_comments
    FOR INSERT
    TO authenticated
    WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can update their own comments"
    ON public.article_comments;

CREATE POLICY "Users can update their own comments"
    ON public.article_comments
    FOR UPDATE
    TO authenticated
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can delete their own comments"
    ON public.article_comments;

CREATE POLICY "Users can delete their own comments"
    ON public.article_comments
    FOR DELETE
    TO authenticated
    USING (auth.uid() = user_id);

-- 11. Bookmark policies
DROP POLICY IF EXISTS "Users can read their own bookmarks"
    ON public.article_bookmarks;

CREATE POLICY "Users can read their own bookmarks"
    ON public.article_bookmarks
    FOR SELECT
    TO authenticated
    USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can add their own bookmarks"
    ON public.article_bookmarks;

CREATE POLICY "Users can add their own bookmarks"
    ON public.article_bookmarks
    FOR INSERT
    TO authenticated
    WITH CHECK (
        auth.uid() = user_id
        AND EXISTS (
            SELECT 1
            FROM public.articles a
            WHERE a.id = article_id
              AND a.status = 'published'
        )
    );

DROP POLICY IF EXISTS "Users can remove their own bookmarks"
    ON public.article_bookmarks;

CREATE POLICY "Users can remove their own bookmarks"
    ON public.article_bookmarks
    FOR DELETE
    TO authenticated
    USING (auth.uid() = user_id);

-- 12. Follow policies
DROP POLICY IF EXISTS "Author follows are publicly readable"
    ON public.author_follows;

CREATE POLICY "Author follows are publicly readable"
    ON public.author_follows
    FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Users can follow from their own account"
    ON public.author_follows;

CREATE POLICY "Users can follow from their own account"
    ON public.author_follows
    FOR INSERT
    TO authenticated
    WITH CHECK (auth.uid() = follower_id);

DROP POLICY IF EXISTS "Users can unfollow from their own account"
    ON public.author_follows;

CREATE POLICY "Users can unfollow from their own account"
    ON public.author_follows
    FOR DELETE
    TO authenticated
    USING (auth.uid() = follower_id);

-- 13. Article engagement counts
CREATE OR REPLACE FUNCTION public.article_engagement_counts(p_article_id UUID)
RETURNS TABLE (
    likes_count BIGINT,
    dislikes_count BIGINT,
    comments_count BIGINT
)
LANGUAGE SQL
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
    SELECT
        (
            SELECT COUNT(*)::BIGINT
            FROM public.article_reactions r
            WHERE r.article_id = p_article_id
              AND r.reaction = 'like'
        ) AS likes_count,
        (
            SELECT COUNT(*)::BIGINT
            FROM public.article_reactions r
            WHERE r.article_id = p_article_id
              AND r.reaction = 'dislike'
        ) AS dislikes_count,
        (
            SELECT COUNT(*)::BIGINT
            FROM public.article_comments c
            WHERE c.article_id = p_article_id
        ) AS comments_count;
$$;

-- 14. Author follower / following / likes / article counts
CREATE OR REPLACE FUNCTION public.author_social_counts(p_author_id UUID)
RETURNS TABLE (
    followers_count BIGINT,
    following_count BIGINT,
    likes_received BIGINT,
    published_articles BIGINT
)
LANGUAGE SQL
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
    SELECT
        (
            SELECT COUNT(*)::BIGINT
            FROM public.author_follows f
            WHERE f.followed_id = p_author_id
        ) AS followers_count,
        (
            SELECT COUNT(*)::BIGINT
            FROM public.author_follows f
            WHERE f.follower_id = p_author_id
        ) AS following_count,
        (
            SELECT COUNT(*)::BIGINT
            FROM public.article_reactions r
            JOIN public.articles a ON a.id = r.article_id
            WHERE a.user_id = p_author_id
              AND a.status = 'published'
              AND r.reaction = 'like'
        ) AS likes_received,
        (
            SELECT COUNT(*)::BIGINT
            FROM public.articles a
            WHERE a.user_id = p_author_id
              AND a.status = 'published'
        ) AS published_articles;
$$;

-- 15. Grant function access
GRANT EXECUTE ON FUNCTION public.article_engagement_counts(UUID)
    TO anon, authenticated;

GRANT EXECUTE ON FUNCTION public.author_social_counts(UUID)
    TO anon, authenticated;

-- Finished.
-- Important: public.articles must already exist and contain:
-- id, user_id, status.
